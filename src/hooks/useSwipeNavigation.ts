import { useRef, useCallback } from 'react';
import { suppressNextClicks, triggerHaptic } from '../services/gestureUtils';

interface UseSwipeNavigationOptions {
  onSwipeLeft?: () => void;  // next month / week
  onSwipeRight?: () => void; // prev month / week
  minDistance?: number;
  maxTimeMs?: number;
  disabled?: boolean;
}

/**
 * Robust swipe navigation hook with direction locking and misoperation safeguards.
 * - Direction locking: Wait for 12px+ movement before locking direction to avoid false locks from thumb arcs.
 * - Speed & Distance hybrid: Detects both deliberate swipes (>=48px) and quick flicks (velocity >= 0.35px/ms).
 * - Click Suppression: Automatically extinguishes stray clicks generated by mobile browsers after swipe/scroll gestures.
 * - Multi-touch cancellation: Instantly cancels when 2+ fingers touch (pinch zoom protection).
 */
export function useSwipeNavigation({
  onSwipeLeft,
  onSwipeRight,
  minDistance = 48,
  maxTimeMs = 550,
  disabled = false,
}: UseSwipeNavigationOptions) {
  const startXRef = useRef<number | null>(null);
  const startYRef = useRef<number | null>(null);
  const startTimeRef = useRef<number>(0);
  const isMultiTouchRef = useRef<boolean>(false);
  const isScrollingVerticallyRef = useRef<boolean>(false);
  const isHorizontalSwipeLockedRef = useRef<boolean>(false);
  const isMovedRef = useRef<boolean>(false);

  const onTouchStart = useCallback(
    (e: React.TouchEvent) => {
      if (disabled) return;
      if (e.touches.length > 1) {
        isMultiTouchRef.current = true;
        startXRef.current = null;
        startYRef.current = null;
        return;
      }
      isMultiTouchRef.current = false;
      isScrollingVerticallyRef.current = false;
      isHorizontalSwipeLockedRef.current = false;
      isMovedRef.current = false;
      startXRef.current = e.touches[0].clientX;
      startYRef.current = e.touches[0].clientY;
      startTimeRef.current = Date.now();
    },
    [disabled]
  );

  const onTouchMove = useCallback(
    (e: React.TouchEvent) => {
      if (disabled || isMultiTouchRef.current || startXRef.current === null || startYRef.current === null) {
        return;
      }
      if (isScrollingVerticallyRef.current) return;

      const currentX = e.touches[0].clientX;
      const currentY = e.touches[0].clientY;
      const dx = Math.abs(currentX - startXRef.current);
      const dy = Math.abs(currentY - startYRef.current);

      if (dx > 8 || dy > 8) {
        isMovedRef.current = true;
      }

      // Early direction locking: require at least 12px of movement to avoid false vertical locking on mobile thumb gestures
      if (!isHorizontalSwipeLockedRef.current && (dx >= 12 || dy >= 12)) {
        if (dy > dx * 1.5) {
          // Distinct vertical scroll movement -> Lock out horizontal swipe for the rest of this gesture
          isScrollingVerticallyRef.current = true;
        } else if (dx > dy * 1.3 && dx >= 14) {
          // Distinct horizontal swipe movement -> Lock in horizontal swipe
          isHorizontalSwipeLockedRef.current = true;
        }
      }
    },
    [disabled]
  );

  const onTouchEnd = useCallback(
    (e: React.TouchEvent) => {
      if (disabled || isMultiTouchRef.current) {
        if (isMovedRef.current) {
          suppressNextClicks(250);
        }
        startXRef.current = null;
        startYRef.current = null;
        return;
      }

      if (isScrollingVerticallyRef.current) {
        if (isMovedRef.current) {
          suppressNextClicks(250);
        }
        startXRef.current = null;
        startYRef.current = null;
        return;
      }

      if (startXRef.current === null || startYRef.current === null) return;

      const duration = Date.now() - startTimeRef.current;
      const endX = e.changedTouches[0].clientX;
      const endY = e.changedTouches[0].clientY;

      const deltaX = endX - startXRef.current;
      const deltaY = endY - startYRef.current;

      const absDeltaX = Math.abs(deltaX);
      const absDeltaY = Math.abs(deltaY);

      // If finger moved noticeably, suppress accidental clicks on elements beneath the release point
      if (absDeltaX > 10 || absDeltaY > 10) {
        suppressNextClicks(350);
      }

      // Rejection: Gesture took too long without fast speed (e.g. slow dragging or holding)
      if (duration > maxTimeMs) {
        startXRef.current = null;
        startYRef.current = null;
        return;
      }

      // Swipe detection:
      // 1. Standard deliberate swipe: distance >= minDistance (48px) and horizontal angle (dx >= dy * 1.3)
      // 2. High-speed flick: velocity >= 0.35 px/ms and distance >= 28px
      const velocity = absDeltaX / Math.max(1, duration);
      const isRegularSwipe = absDeltaX >= minDistance && absDeltaX >= absDeltaY * 1.3;
      const isQuickFlick = absDeltaX >= 28 && absDeltaX >= absDeltaY * 1.2 && velocity >= 0.35 && duration <= 280;

      if (isRegularSwipe || isQuickFlick) {
        // High confidence swipe completed: suppress subsequent click events on the screen
        suppressNextClicks(500);
        triggerHaptic('light');

        if (deltaX < 0) {
          onSwipeLeft?.();
        } else {
          onSwipeRight?.();
        }
      }

      startXRef.current = null;
      startYRef.current = null;
      isMovedRef.current = false;
    },
    [disabled, minDistance, maxTimeMs, onSwipeLeft, onSwipeRight]
  );

  const onTouchCancel = useCallback(() => {
    startXRef.current = null;
    startYRef.current = null;
    isMovedRef.current = false;
    isScrollingVerticallyRef.current = false;
    isHorizontalSwipeLockedRef.current = false;
  }, []);

  return {
    onTouchStart,
    onTouchMove,
    onTouchEnd,
    onTouchCancel,
  };
}
